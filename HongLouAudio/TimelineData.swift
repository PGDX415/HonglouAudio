import Foundation

// MARK: - Timeline Event

struct TimelineEvent: Identifiable, Hashable {
    let id = UUID()
    let chapterNumber: Int
    let eventIndex: Int
    let title: String
    let detail: String

    func hash(into hasher: inout Hasher) {
        hasher.combine(id)
    }
    static func == (lhs: TimelineEvent, rhs: TimelineEvent) -> Bool {
        lhs.id == rhs.id
    }
}

// MARK: - Events Data

struct TimelineStore {
    /// Returns events grouped by chapter number, sorted by eventIndex.
    static var allEvents: [Int: [TimelineEvent]] {
        Dictionary(grouping: events, by: { $0.chapterNumber })
    }

    /// Sorted chapter numbers that have events.
    static var chapterNumbers: [Int] {
        Array(allEvents.keys).sorted()
    }

    /// Flattened sorted list of all events.
    static var events: [TimelineEvent] {
        rawEvents.enumerated().compactMap { index, tuple in
            guard !tuple.title.isEmpty else { return nil }
            return TimelineEvent(
                chapterNumber: tuple.chapter,
                eventIndex: index,
                title: tuple.title,
                detail: tuple.detail
            )
        }
    }
}

