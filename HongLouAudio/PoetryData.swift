import SwiftUI

// MARK: - Poem Model

enum PoemCategory: String, CaseIterable, Codable {
    case 诗 = "诗"
    case 词 = "词"
    case 曲 = "曲"
    case 诔文 = "诔文"
    case 歌谣 = "歌谣"
    case 判词 = "判词"

    var iconName: String {
        switch self {
        case .诗: return "paintbrush"
        case .词: return "music.quarternote.3"
        case .曲: return "music.note.list"
        case .诔文: return "scroll"
        case .歌谣: return "waveform"
        case .判词: return "sparkles"
        }
    }

    var color: Color {
        switch self {
        case .诗: return Color(red: 0.6, green: 0.2, blue: 0.2)
        case .词: return Color(red: 0.2, green: 0.4, blue: 0.6)
        case .曲: return Color(red: 0.5, green: 0.3, blue: 0.7)
        case .诔文: return Color(red: 0.35, green: 0.35, blue: 0.35)
        case .歌谣: return Color(red: 0.15, green: 0.5, blue: 0.4)
        case .判词: return Color(red: 0.7, green: 0.45, blue: 0.1)
        }
    }
}

